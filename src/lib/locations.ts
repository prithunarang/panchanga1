/** Full IANA timezone list, used for the manual/advanced timezone picker. */
export function allTimezones(): string[] {
  try {
    // Available in modern browsers and Node 18+; falls back to a curated list otherwise.
    const supported = (Intl as unknown as { supportedValuesOf?: (key: string) => string[] }).supportedValuesOf;
    if (supported) return supported("timeZone");
  } catch {
    // fall through to fallback list
  }
  return Array.from(new Set(PRESET_LOCATIONS.map((l) => l.timezone))).sort();
}

export function searchLocations(query: string): Location[] {
  const q = query.trim().toLowerCase();
  if (!q) return PRESET_LOCATIONS;
  return PRESET_LOCATIONS.filter(
    (loc) =>
      loc.city.toLowerCase().includes(q) ||
      loc.country.toLowerCase().includes(q) ||
      loc.admin?.toLowerCase().includes(q)
  );
}

